// Strict RFC 9110 §13.1.2 `If-None-Match` evaluation (ADR-038 §4): the field
// value is either `*` or a list of entity tags, compared with weak comparison
// for GET — the weak prefix (`W/`) is ignored on both sides while the opaque
// tag itself compares case-sensitively. Malformed candidates are ignored —
// they can never produce a false 304 — and the whole header is ignored past
// a bounded input size (DoS posture: a single pass over a bounded string).

/** Exclusive cap on the accepted `If-None-Match` field value length (characters). */
const MAX_IF_NONE_MATCH_LENGTH = 4096;

// entity-tag = [ weak ] opaque-tag ; weak prefix is the case-sensitive %s"W/"
// opaque-tag = DQUOTE *etagc DQUOTE
// etagc = %x21 / %x23-7E / obs-text  (everything except DQUOTE and control
// characters — note this INCLUDES commas and backslashes inside the quotes,
// which a naive comma split corrupts).
const DQUOTE = '"';

/**
 * Whether the request's `If-None-Match` header matches the current entity
 * tag under weak comparison. `headerValue` may be a string, a multi-value
 * array, or absent; anything that is not a non-empty value evaluates to
 * `false`. `etag` is the current `W/"…"` validator.
 */
export function ifNoneMatchSatisfied(headerValue: unknown, etag: string): boolean {
  if (typeof headerValue === 'string') {
    return evaluate(headerValue, etag);
  }
  if (Array.isArray(headerValue)) {
    // Multiple header lines combine into one list (RFC 9110 §5.5) and the
    // bounded input size applies to the COMBINED field value, not each line
    // (Wave 27 SEC-01). Each line is still evaluated as its own list — a
    // tag cannot span lines — and an early match wins before the combined
    // budget trips; a non-string member can never match.
    let combinedLength = 0;
    for (const value of headerValue) {
      if (typeof value !== 'string') continue;
      combinedLength += value.length;
      if (combinedLength > MAX_IF_NONE_MATCH_LENGTH) return false;
      if (evaluate(value, etag)) return true;
    }

    return false;
  }

  return false;
}

function evaluate(fieldValue: string, etag: string): boolean {
  const trimmed = fieldValue.trim();
  if (trimmed === '' || trimmed.length > MAX_IF_NONE_MATCH_LENGTH) {
    return false;
  }

  const current = parseEntityTag(etag);
  if (current === undefined) {
    // The server-side tag is always generated by `weakEtagFor` and always
    // parses; an unparseable current tag is treated as no match (fail-safe).
    return false;
  }

  // RFC 9110: the field value is `*` OR an entity-tag list — never both —
  // so the wildcard is honored only as the entire field value.
  if (trimmed === '*') {
    return true;
  }

  let start = 0;
  let inQuotes = false;
  for (let index = 0; index <= trimmed.length; index++) {
    const character = trimmed[index];
    // Commas inside the quoted opaque tag are literal etagc characters and
    // must not split the list.
    if (character === DQUOTE) {
      inQuotes = !inQuotes;
    }
    if ((character === ',' || index === trimmed.length) && !inQuotes) {
      const candidate = parseEntityTag(trimmed.slice(start, index).trim());
      if (candidate !== undefined && candidate.opaque === current.opaque) {
        return true;
      }
      start = index + 1;
    }
  }

  return false;
}

/**
 * Parses one entity-tag candidate: `W/"…"` (weak) or `"…"` (strong) — the
 * opaque tag between the quotes is what weak comparison evaluates. Returns
 * `undefined` for anything malformed — an unquoted tag, a bare `W/`, an
 * unterminated quote, control or non-latin1 characters — which the list
 * evaluation then ignores (safe failure, ADR-038 §4). `""` is grammatically
 * valid and can never match a generated tag, so it is accepted and simply
 * never matches.
 */
function parseEntityTag(candidate: string): { opaque: string } | undefined {
  let index = 0;
  // The weak prefix is the case-sensitive %s"W/".
  if (candidate.startsWith('W/')) {
    index = 2;
  }

  if (candidate[index] !== DQUOTE) {
    return undefined;
  }

  let opaque = '';
  for (index = index + 1; index < candidate.length; index++) {
    const code = candidate.charCodeAt(index);
    if (code === 0x22) {
      // The closing quote must be the last character of the candidate.
      return index === candidate.length - 1 ? { opaque } : undefined;
    }
    if (!isEtagc(code)) {
      return undefined;
    }
    opaque += candidate[index];
  }

  return undefined;
}

function isEtagc(code: number): boolean {
  // %x21 / %x23-7E / obs-text (%x80-FF): printable, no DQUOTE, no controls.
  return code === 0x21 || (code >= 0x23 && code <= 0x7e) || (code >= 0x80 && code <= 0xff);
}
